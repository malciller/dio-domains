(** Maker fee for one asset without network: explicit config value, else the
    fee cache warmed by the refresher, else the venue's registered default. *)
let fees_now (t : Oracle_tasks.task) : Oracle_core.fee_model =
  let maker =
    match t.config.maker_fee with
    | Some f -> f
    | None ->
      (match Hashtbl.find_opt Oracle_fees.fee_cache (t.exchange, t.symbol) with
       | Some (m, _) -> m
       | None -> fst (Oracle_fees.venue_default_fees t.exchange t.symbol))
  in
  { Oracle_core.maker_fee = Float.max 0.0 maker; fee_in_base_buy = false }
;;

