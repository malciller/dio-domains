(** A venue account: pools never cross these. *)
type account =
  { a_exchange : string
  ; a_testnet : bool
  ; a_quote : string
  }

let account_id (a : account) =
  account_key_of ~exchange:a.a_exchange ~testnet:a.a_testnet ~quote:a.a_quote
;;

let account_of_task (t : Oracle_tasks.task) : account =
  let _, quote = split_symbol t.symbol in
  { a_exchange = t.exchange; a_testnet = t.config.testnet; a_quote = quote }
;;

let same_account x y =
  String.equal x.a_exchange y.a_exchange
  && x.a_testnet = y.a_testnet
  && String.equal x.a_quote y.a_quote
;;

(** Tasks grouped by venue account, preserving config.json order (priority
    order within each account). *)
let group_by_account (tasks : Oracle_tasks.task list)
  : (account * Oracle_tasks.task list) list
  =
  let accounts = ref [] in
  List.iter
    (fun (task : Oracle_tasks.task) ->
       let account = account_of_task task in
       if not (List.exists (same_account account) !accounts)
       then accounts := account :: !accounts)
    tasks;
  let accounts = List.rev !accounts in
  List.map
    (fun account ->
       ( account
       , List.filter
           (fun (task : Oracle_tasks.task) -> same_account account (account_of_task task))
           tasks ))
    accounts
;;

(** Last known balance snapshots per account id, warmed by the background
    refresher and the initial pass. *)
type pool_state =
  { snap : Oracle_balances.snapshot
  ; ps_epoch : int
  ; fetched_at : float
  }

let pool_cache : (string, pool_state) Hashtbl.t = Hashtbl.create 8
let clear_pool_cache () = Hashtbl.reset pool_cache

(** Fetch balances for one task (live store first, REST fallback) into the
    pool cache. Network - called from the refresher and startup only. *)
let refresh_balance_of_task (task : Oracle_tasks.task) : unit Lwt.t =
  let account = account_of_task task in
  let id = account_id account in
  Lwt.catch
    (fun () ->
       Oracle_balances.fetch_task_live task
       >|= function
       | Error error ->
         Logging.debug
           ~section
           (Printf.sprintf "balance refresh failed for %s: %s" id error)
       | Ok snapshot ->
         Atomic.incr balance_epoch;
         Hashtbl.replace
           pool_cache
           id
           { snap = snapshot
           ; ps_epoch = Atomic.get balance_epoch
           ; fetched_at = Unix.gettimeofday ()
           })
    (fun exn ->
       Logging.debug
         ~section
         (Printf.sprintf "balance refresh failed for %s: %s" id (Printexc.to_string exn));
       Lwt.return ())
;;

(** Available quote for an account RIGHT NOW: live store when present,
    else the cached snapshot; plus in-process pending deltas measured at the
    snapshot's epoch. Zero network. *)
let available_quote_now (a : account) : float option =
  let id = account_id a in
  let snap_opt =
    match
      Oracle_balances.snapshot_of_live_store
        ~exchange:a.a_exchange
        ~testnet:a.a_testnet
        ()
    with
    | Some snap -> Some snap
    | None -> Option.map (fun p -> p.snap) (Hashtbl.find_opt pool_cache id)
  in
  match snap_opt with
  | None -> None
  | Some snap ->
    let epoch =
      match Hashtbl.find_opt pool_cache id with
      | Some p
        when Option.is_none
               (Oracle_balances.snapshot_of_live_store
                  ~exchange:a.a_exchange
                  ~testnet:a.a_testnet
                  ()) -> p.ps_epoch
      | _ -> Atomic.get balance_epoch
    in
    let dq, pending = pending_deltas id epoch in
    if pending <> [] then prune_pending id epoch;
    Some (Float.max 0.0 (Oracle_balances.available_quote snap ~quote:a.a_quote +. dq))
;;

(** Available base for one symbol right now (same sources), minus nothing:
    reserved_base is excluded upstream by the execution layer's
    available_trading_balance. Resting sells are subtracted separately via
    the open-order registry. Zero network. *)
let available_base_now (a : account) ~(symbol : string) : float option =
  let id = account_id a in
  let snap_opt =
    match
      Oracle_balances.snapshot_of_live_store
        ~exchange:a.a_exchange
        ~testnet:a.a_testnet
        ()
    with
    | Some snap -> Some snap
    | None -> Option.map (fun p -> p.snap) (Hashtbl.find_opt pool_cache id)
  in
  match snap_opt with
  | None -> None
  | Some snap ->
    let base, _ = split_symbol symbol in
    let epoch =
      match Hashtbl.find_opt pool_cache id with
      | Some p
        when Option.is_none
               (Oracle_balances.snapshot_of_live_store
                  ~exchange:a.a_exchange
                  ~testnet:a.a_testnet
                  ()) -> p.ps_epoch
      | _ -> Atomic.get balance_epoch
    in
    let _, pending = pending_deltas id epoch in
    let db =
      List.fold_left
        (fun acc (e : pool_event) ->
           if String.equal e.pe_base_asset base then acc +. e.pe_delta_base else acc)
        0.0
        pending
    in
    if pending <> [] then prune_pending id epoch;
    Some (Float.max 0.0 (Oracle_balances.available_asset snap ~asset:base +. db))
;;

