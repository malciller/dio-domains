(* The pass *)
(* ------------------------------------------------------------------ *)

let string_of_regime = function
  | Oracle_core.Normal -> "normal"
  | Oracle_core.Floor_extension -> "floor extension"
  | Oracle_core.Unprecedented_lows -> "unprecedented lows"
;;

let string_of_branch = function
  | Oracle_core.Reachable -> "reachable"
  | Oracle_core.Surplus -> "surplus"
  | Oracle_core.Unreachable -> "unreachable"
;;

(** One venue re-resolve: walk the account's strategies in config order, size each against
    the free pool remaining at its turn, and deduct each funded need. A starved survivor
    (survival met but next buy does not fit) reclaims its shortfall by flagging the
    minimum set of lower-priority resting buys for cancellation; the freed quote is
    reserved for it and lower-priority strategies are held inactive until the cancels land
    and the cancel event wakes the next pass to fund it. Resting buys are already
    committed, so they do not consume free quote.

    Once a cascade is issued for a senior, a per-account reservation is kept across passes
    (see [reclaim_reservations]) so every strictly-lower-priority strategy stays held
    inactive until the senior is actually funded - not merely for the one pass that issued
    the cancel. Without it the store/pool window (order gone from the exec feed before the
    balance feed grows) let a junior re-fund from the quote being freed, restarting the
    cascade. *)

(* ------------------------------------------------------------------ *)
(* Priority reclaim reservations *)
(* ------------------------------------------------------------------ *)

(** A senior strategy's standing claim on capital being released by a lower-priority
    cancel.

    The reservation must outlive the cancel ack. The order leaves the exec feed before the
    balance feed shows the freed quote; releasing on "flagged buy gone" lets a junior
    re-place into that window and restarts the cascade. The reservation therefore clears
    only when the senior actually funds (or stops being a survivor), with a TTL as the
    failure backstop if the freed quote never appears. *)
type reclaim_reservation =
  { rr_senior : string (** [key_of_task] of the senior awaiting the freed quote. *)
  ; rr_reserved : float (** Quote reserved for it (its next buy's need). *)
  ; rr_cancelled_keys : string list
  (** Strategies whose resting buys the cascade flagged (diagnostics). *)
  ; rr_at : int64 (** Monotonic ns when the reservation was taken, for the TTL. *)
  }

let reclaim_ttl_s = 30.0
let reclaim_ttl_ns = Int64.of_float (reclaim_ttl_s *. 1e9)

(** Per-account reservation, keyed by [account_id]. Written and read only on the pass
    loop. *)
let reclaim_reservations : (string, reclaim_reservation) Hashtbl.t = Hashtbl.create 8

(** One retry fiber per account while a reservation is live: the cancel wake can land
    before the venue's stores drop the freed order. *)
let reclaim_retrying : (string, unit) Hashtbl.t = Hashtbl.create 8

let rec retry_reclaim acct_id =
  if Hashtbl.mem reclaim_reservations acct_id
  then (
    Lwt_unix.sleep 0.25
    >>= fun () ->
    request_pass ();
    retry_reclaim acct_id)
  else (
    Hashtbl.remove reclaim_retrying acct_id;
    Lwt.return_unit)
;;

let start_reclaim_retry acct_id =
  if not (Hashtbl.mem reclaim_retrying acct_id)
  then (
    Hashtbl.add reclaim_retrying acct_id ();
    Lwt.async (fun () -> retry_reclaim acct_id))
;;

let run_account_pass
  ~(config : runtime_config)
  ~(account : account)
  ~(tasks : Oracle_tasks.task list)
  : decision list Lwt.t
  =
  match account_snapshot_of account with
  | None ->
    Logging.warn_f
      ~section
      "no balance data for %s yet; keeping last-known-good decisions"
      (account_id account);
    (* Keep prior decisions for this venue unchanged. *)
    Lwt.return
      (List.filter
         (fun (d : decision) ->
           List.exists
             (fun (t : Oracle_tasks.task) ->
               String.equal t.exchange d.exchange && String.equal t.symbol d.symbol)
             tasks)
         (decisions ()))
  | Some acs ->
    let pool = available_quote_in account acs in
    let acct_id = account_id account in
    let reservation =
      match Hashtbl.find_opt reclaim_reservations acct_id with
      | None -> None
      | Some r ->
        if Int64.sub (Mtime_clock.now_ns ()) r.rr_at > reclaim_ttl_ns
        then (
          Hashtbl.remove reclaim_reservations acct_id;
          Logging.warn_f
            ~section
            "reclaim reservation expired for %s: %s did not fund within %.0fs"
            acct_id
            r.rr_senior
            reclaim_ttl_s;
          None)
        else Some r
    in
    let reserved_senior = Option.map (fun r -> r.rr_senior) reservation in
    (* Open-order summaries and config bounds are invariant across the pass, so resolve
       them once here instead of 2-3x in the sizing loop. *)
    let task_rows =
      List.map
        (fun (t : Oracle_tasks.task) ->
          let summary = open_orders_summary ~exchange:t.exchange ~symbol:t.symbol in
          let knobs = effective_knobs ~config ~symbol:t.symbol in
          let qty_raw = float_of_string_opt t.config.qty |> Option.value ~default:0.0 in
          let bounds =
            { Oracle_core.qty = Float.max 1e-12 qty_raw
            ; qty_cap_mult = Float.max 1.0 knobs.k_qty_cap_mult
            ; gi_min = fst t.config.grid_interval
            ; gi_max = snd t.config.grid_interval
            }
          in
          t, summary, knobs, bounds)
        tasks
    in
    let committed_venue_buys =
      List.fold_left
        (fun acc (_, (_, committed, _), _, _) -> acc +. committed)
        0.0
        task_rows
    in
    let total_venue_quote = pool +. committed_venue_buys in
    let key_of_task (t : Oracle_tasks.task) =
      Printf.sprintf "%s|%s" t.exchange t.symbol
    in
    (* Account-local priority by key (config presentation order), matching the walk order
       the reclaim logic uses. *)
    let priority_of_key : (string, int) Hashtbl.t = Hashtbl.create 8 in
    List.iteri
      (fun i ((t : Oracle_tasks.task), _, _, _) ->
        Hashtbl.replace priority_of_key (key_of_task t) i)
      task_rows;
    (* Standing reservation for a senior whose cancelled quote is draining: every strategy
       of strictly lower priority is held until it funds. Dropped when the senior is no
       longer among this account's tasks. *)
    let reserved_priority =
      ref
        (match reserved_senior with
         | Some k ->
           (match Hashtbl.find_opt priority_of_key k with
            | Some p -> Some p
            | None ->
              Hashtbl.remove reclaim_reservations acct_id;
              None)
         | None -> None)
    in
    (* Per-strategy reclaim candidates: the lower-priority (later config position)
       strategies holding resting buys, precomputed once. The cascade draws only from
       these, so a senior strategy can never reclaim a peer's or its own capital. *)
    let lower_claims =
      let indexed = List.mapi (fun i row -> i, row) task_rows in
      List.map
        (fun (i, ((t : Oracle_tasks.task), _, _, _)) ->
          let claims =
            List.filter_map
              (fun (j, ((lt : Oracle_tasks.task), (_, lcommitted, _), _, _)) ->
                if j > i && lcommitted > 0.0
                then
                  Some
                    { Oracle_pools.id = key_of_task lt
                    ; priority = j
                    ; need_quote = 0.0
                    ; resting_buy_quote = lcommitted
                    }
                else None)
              indexed
          in
          key_of_task t, claims)
        indexed
    in
    (* One reclaim wave per pass: once a starved senior strategy has a feasible
       cancellation plan, lower-priority strategies are held inactive until the cancels
       land and the cancel event wakes a fresh pass. *)
    let reclaim_active = ref false in
    let flagged : string list ref = ref [] in
    let remaining = ref pool in
    let built
      : (Oracle_tasks.task * decision * float * float * Oracle_pipeline.outcome option)
          list
          ref
      =
      ref []
    in
    List.iter
      (fun ( (t : Oracle_tasks.task)
           , (resting_buy, committed_buy, resting_sell)
           , knobs
           , bounds ) ->
        let t_asset = Mtime_clock.now_ns () in
        (* No usable data yet: publish nothing rather than a fabricated zero inactive
           decision, which would open the domain's startup gate on values never computed.
           The asset joins the surface on the next pass after refresh delivers history and
           balances. *)
        let skip_asset reason =
          record_asset_latency t.symbol (span_from t_asset) (fun () -> reason);
          Logging.debug_f
            ~section
            "%s/%s: %s; no decision published this pass"
            t.exchange
            t.symbol
            reason
        in
        match Hashtbl.find_opt history_cache (t.exchange, t.symbol) with
        | None -> skip_asset "history unavailable"
        | Some series ->
          let fallback_close =
            Option.value (Oracle_pipeline.current_price_of_series series) ~default:0.0
          in
          if fallback_close <= 0.0
          then skip_asset "history has no usable close"
          else (
            let current =
              live_buy_anchor
                ~exchange:t.exchange
                ~symbol:t.symbol
                ~fallback:fallback_close
            in
            let effective_quote =
              if resting_buy then !remaining +. committed_buy else !remaining
            in
            let inputs : Oracle_pipeline.inputs =
              { exchange = t.exchange
              ; symbol = t.symbol
              ; bars = series.bars
              ; current_price = current
              ; available_quote = effective_quote
              ; sell_qty = 0.0
              ; bounds
              ; target_survival = knobs.k_target_survival
              ; min_active_dsurv = knobs.k_min_active_dsurv
              ; lookback_days = knobs.k_lookback_days
              ; fees = fees_now t
              ; has_resting_buy = resting_buy
              }
            in
            let refs_opt =
              match Hashtbl.find_opt references_cache (t.exchange, t.symbol) with
              | Some (w, r) when w = knobs.k_lookback_days -> Some r
              | _ ->
                (match
                   Oracle_core.references_of
                     ~window_days:knobs.k_lookback_days
                     ~bars:series.bars
                 with
                 | Some r as some ->
                   Hashtbl.replace
                     references_cache
                     (t.exchange, t.symbol)
                     (knobs.k_lookback_days, r);
                   some
                 | None -> None)
            in
            match
              match refs_opt with
              | None -> None
              | Some refs -> Oracle_pipeline.decide_from_refs ~refs ~inputs
            with
            | None -> skip_asset "references unavailable"
            | Some o ->
              let base_avail = available_base_in account ~symbol:t.symbol acs in
              let sell_qty =
                Oracle_pools.sell_qty_of
                  ~base_balance:base_avail
                  ~reserved_base:0.0
                  ~resting_sell_base:resting_sell
              in
              let reason =
                if o.decision.active
                then ""
                else if o.resolution.d_surv < knobs.k_min_active_dsurv
                then
                  Printf.sprintf
                    "d_surv %.3f below min_active_dsurv %.3f"
                    o.resolution.d_surv
                    knobs.k_min_active_dsurv
                else "awaiting reactivation: quote does not cover buy"
              in
              let d : decision =
                { exchange = t.exchange
                ; symbol = t.symbol
                ; active = o.decision.active
                ; grid_interval = o.decision.grid_interval
                ; buy_qty = o.decision.buy_qty
                ; sell_qty
                ; max_drawdown_pct = o.refs.max_drawdown_pct
                ; reason
                ; d_surv = o.resolution.d_surv
                ; exhaustion_price =
                    Oracle_core.exhaustion_price_of
                      ~current
                      ~funded_floor:o.runway.funded_floor
                      ~d_surv:o.resolution.d_surv
                ; regime = string_of_regime o.runway.regime
                ; branch = string_of_branch o.resolution.branch
                ; cancel_resting_buys = false
                ; updated_at = Unix.gettimeofday ()
                }
              in
              let need = d.buy_qty *. current in
              let key = key_of_task t in
              let survival_active =
                o.resolution.d_surv >= knobs.k_min_active_dsurv || resting_buy
              in
              let is_reserved_senior =
                match reserved_senior with
                | Some k -> String.equal k key
                | None -> false
              in
              let priority = Hashtbl.find priority_of_key key in
              let d =
                if Oracle_pools.held_for_reservation
                     ~reserved_priority:!reserved_priority
                     ~priority
                then
                  (* The reserved senior's cascade is draining and this strategy ranks
                     below it. Hold it inactive so it cannot re-place from the very quote
                     being freed (see [Oracle_pools.held_for_reservation]). *)
                  { d with
                    active = false
                  ; reason = "capital reserved for higher-priority strategy"
                  }
                else if List.mem key !flagged
                then
                  { d with
                    active = false
                  ; reason = "capital reallocated to higher-priority strategy"
                  }
                else if d.active
                then (
                  (* Funded strategies tie their next buy's quote; starved ones pass
                     capacity down. Resting buys are already committed in the pool, so
                     only fresh active placements consume free quote. *)
                  if (not resting_buy) && need <= !remaining +. 1e-9
                  then remaining := !remaining -. need;
                  (* The reserved senior just funded: the reclaim completed, release the
                     cross-pass hold so lower-priority strategies resume normally. *)
                  if is_reserved_senior
                  then (
                    Hashtbl.remove reclaim_reservations acct_id;
                    reserved_priority := None;
                    Logging.info_f
                      ~section
                      "reclaim reservation cleared for %s/%s: %s funded ($%.2f reserved)"
                      t.exchange
                      t.symbol
                      key
                      (Option.fold ~none:0.0 ~some:(fun r -> r.rr_reserved) reservation));
                  d)
                else if survival_active && not !reclaim_active
                then (
                  (* Starved survivor: evaluate lower-priority resting buys and cancel the
                     minimum set that frees this strategy's shortfall. On success the
                     freed quote is reserved for this strategy, lower-priority strategies
                     are held inactive for the rest of the pass, and the cancel event
                     wakes the next pass to fund it - no timed run required. *)
                  let claims =
                    Option.value (List.assoc_opt key lower_claims) ~default:[]
                  in
                  let available = !remaining in
                  let plan =
                    Oracle_pools.cascade ~available ~need ~trigger_id:key ~claims
                  in
                  if plan <> []
                  then (
                    reclaim_active := true;
                    flagged := List.rev_append plan !flagged;
                    remaining := 0.0;
                    (* Reserve the freed quote for this senior across passes. The cancel
                       lands on the exec feed before the balance feed reflects the
                       released quote; in that window the senior has no resting buy left
                       to point the cascade at, while lower-priority strategies could
                       re-fund from the same quote. *)
                    Hashtbl.replace
                      reclaim_reservations
                      acct_id
                      { rr_senior = key
                      ; rr_reserved = need
                      ; rr_cancelled_keys = plan
                      ; rr_at = Mtime_clock.now_ns ()
                      };
                    start_reclaim_retry acct_id;
                    reserved_priority := Some priority;
                    Logging.info_f
                      ~section
                      "cancellation cascade for %s/%s (need $%.2f vs $%.2f available): \
                       cancelling resting buys of [%s]"
                      t.exchange
                      t.symbol
                      need
                      available
                      (String.concat ", " plan);
                    { d with
                      active = false
                    ; reason = "awaiting reactivation: quote does not cover buy"
                    })
                  else
                    (* No fresh claim to cancel - typically the freed order already left
                       the store while the pool has not yet grown. The standing
                       reservation keeps every lower-priority strategy held across the
                       next passes so the released quote is not handed back to them. *)
                    d)
                else (
                  (* Inactive and no longer survival-eligible: any standing reservation
                     for this strategy is moot. *)
                  if is_reserved_senior && not survival_active
                  then (
                    Hashtbl.remove reclaim_reservations acct_id;
                    reserved_priority := None);
                  d)
              in
              record_asset_latency t.symbol (span_from t_asset) (fun () ->
                if d.active then "active" else "inactive");
              built := (t, d, need, current, Some o) :: !built))
      task_rows;
    let built_rev = List.rev !built in
    let global_index (lt : Oracle_tasks.task) =
      let rec pos (k : int) (l : Oracle_tasks.task list) : int =
        match l with
        | [] -> k
        | x :: r ->
          if String.equal x.symbol lt.symbol && String.equal x.exchange lt.exchange
          then k
          else pos (k + 1) r
      in
      pos 0 tasks
    in
    (* Shared venue drawdown simulation: active strategies execute 1 order sequentially in
       priority order until venue quote capital is exhausted. *)
    let active_sim : Oracle_pools.sim_strategy list =
      List.filter_map
        (fun ((t, d, _, current, _) :
               Oracle_tasks.task
               * decision
               * float
               * float
               * Oracle_pipeline.outcome option) ->
          if d.active
          then
            Some
              { Oracle_pools.id = key_of_task t
              ; priority = global_index t
              ; current
              ; grid_interval = d.grid_interval
              ; buy_qty = d.buy_qty
              ; maker_fee = (fees_now t).maker_fee
              }
          else None)
        built_rev
    in
    let sim_dsurvs =
      Oracle_pools.simulate_drawdown_survival ~total_quote:total_venue_quote active_sim
    in
    let built_rev =
      List.map
        (fun ((t, d, need, current, outcome) :
               Oracle_tasks.task
               * decision
               * float
               * float
               * Oracle_pipeline.outcome option) ->
          if d.active
          then (
            (* Active strategies report the venue-simulated survival: the shared-capital
               drawdown sim in priority order. Its P_funded is the exhaustion price
               matching that d_surv. *)
            match List.assoc_opt (key_of_task t) sim_dsurvs with
            | Some { Oracle_pools.d_surv; funded_price } ->
              ( t
              , { d with d_surv; exhaustion_price = funded_price }
              , need
              , current
              , outcome )
            | None -> t, { d with d_surv = 0.0 }, need, current, outcome)
          else t, { d with d_surv = 0.0 }, need, current, outcome)
        built_rev
    in
    Lwt.return
      (List.map
         (fun ((_, d, _, _, _) :
                Oracle_tasks.task
                * decision
                * float
                * float
                * Oracle_pipeline.outcome option) ->
           if List.mem (Printf.sprintf "%s|%s" d.exchange d.symbol) !flagged
           then
             { d with
               cancel_resting_buys = true
             ; active = false
             ; reason = "capital reallocated to higher-priority strategy"
             }
           else d)
         built_rev)
;;

(** One full re-resolve across all venues. *)
let run_pass
  ~(config : runtime_config)
  ~(tasks : Oracle_tasks.task list)
  ~(on_publish : string list -> decision list -> unit)
  : unit Lwt.t
  =
  (* Consume the venue execution rings first: fills and terminal cancels are pool deltas
     this pass must size against. Each reader owns its cursor, so the domain's drain is
     unaffected. Then move the queued deltas into the per-account pending table that
     [available_quote_in] overlays on the live snapshot. *)
  drain_execution_events tasks;
  drain_pool_events ();
  let started = Mtime_clock.now_ns () in
  let groups = group_by_account tasks in
  Lwt_list.fold_left_s
    (fun acc (account, tsks) ->
      run_account_pass ~config ~account ~tasks:tsks >|= fun ds -> ds :: acc)
    []
    groups
  >>= fun decision_lists ->
  publish ~on_publish (List.concat (List.rev decision_lists));
  Atomic.incr pass_count;
  let pass_span = span_from started in
  Latency_profiler.record (Lazy.force engine_profs).prof_pass pass_span;
  let _ = Latency_profiler.snapshot_and_reset (Lazy.force engine_profs).prof_pass in
  List.iter
    (fun (t : Oracle_tasks.task) ->
      ignore (Latency_profiler.snapshot_and_reset (asset_profiler_of t.symbol)))
    tasks;
  Logging.debug_f
    ~section
    "pass %d done (%d assets, %.1fms)"
    (Atomic.get pass_count)
    (List.length tasks)
    (Mtime.Span.to_float_ns pass_span /. 1e9 *. 1000.0);
  Lwt.return ()
;;

