(* Oracle_runtime - event-driven capital allocation across venues.

   One pass re-resolves every configured asset: merged history -> windowed references ->
   runway -> survival-replay parameter search -> decision record, sized against per-venue
   pools walked in config presentation order (first = highest priority; capacity passes
   down; a lower-priority strategy is never starved while quote exists). Pools are per
   venue and never cross venues.

   Hot path is pure arithmetic over in-process state:
   - history is cached and refreshed on the [refresh_seconds] background poll;
   - balances come from the websocket-fed live store, else the last fetched snapshot,
     adjusted in process by the fill/cancel deltas drained from the venue execution rings,
     so events never wait on network;
   - live prices read the in-process top-of-book with a sane-band check against the last
     bar close.

   Events (fills, cancels, balance changes, explicit requests) coalesce into one
   re-resolve.

   Strategy-facing contract: four values per asset ([active], [grid_interval], [buy_qty],
   [sell_qty]), generated by the pass below and consumed everywhere. Values are emitted
   for inactive strategies too, for visibility, pool accounting and reactivation
   eligibility. Normalization happens at the exchange layer. [reason], [d_surv], [regime]
   and [branch] are diagnostics for logs and dio-oracle output only. *)

module Exchange = Dio_exchange.Exchange_intf
open Lwt.Infix

let section = "oracle_runtime"

