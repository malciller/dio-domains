(* Background refresh                                                 *)
(* ------------------------------------------------------------------ *)

(** Refreshes histories + balances for every task once (network). Sets
    [materialized] after the first attempt and wakes the runtime when any
    history changed or balances arrived. *)
let refresh_once ~(offline : bool) ~(tasks : Oracle_tasks.task list) : unit Lwt.t =
  let started = Mtime_clock.now_ns () in
  Lwt_list.iter_s
    (fun (t : Oracle_tasks.task) ->
       refresh_asset_history ~offline ~exchange:t.exchange ~symbol:t.symbol
       >>= fun changed ->
       if changed then Atomic.set history_changed true;
       Lwt.return ())
    tasks
  >>= fun () ->
  let t_bal = Mtime_clock.now_ns () in
  let accounts = group_by_account tasks |> List.map fst in
  Lwt_list.iter_s
    (fun account ->
       match
         List.find_opt
           (fun (t : Oracle_tasks.task) -> same_account account (account_of_task t))
           tasks
       with
       | None -> Lwt.return ()
       | Some task -> refresh_balance_of_task task)
    accounts
  >>= fun () ->
  Latency_profiler.record (Lazy.force engine_profs).prof_balance (span_from t_bal);
  Atomic.incr refresh_generation;
  Atomic.set materialized_ref (Some { m_epoch = Atomic.get refresh_generation });
  Latency_profiler.record (Lazy.force engine_profs).prof_fetch (span_from started);
  let _ = Latency_profiler.snapshot_and_reset (Lazy.force engine_profs).prof_balance in
  let _ = Latency_profiler.snapshot_and_reset (Lazy.force engine_profs).prof_fetch in
  request_pass ();
  Lwt.return ()
;;

let rec refresh_loop
          ~(offline : bool)
          ~(config : runtime_config)
          ~(tasks : Oracle_tasks.task list)
  : unit Lwt.t
  =
  if is_stopped ()
  then Lwt.return ()
  else
    refresh_once ~offline ~tasks
    >>= fun () ->
    wait_until
      ~deadline:(Unix.gettimeofday () +. config.refresh_seconds)
      ~generation:(Atomic.get pass_requested)
      ()
    >>= fun () -> refresh_loop ~offline ~config ~tasks
;;

(* ------------------------------------------------------------------ *)
(* Main loop                                                          *)
(* ------------------------------------------------------------------ *)

(** Runs the oracle until shutdown: initial background refresh, then a
    wake-driven pass loop. Events (fills, cancels, balance changes,
    [request_pass]) coalesce into single re-resolves; the refresh cadence is
    the fallback poll. Returns when [shutdown] is requested. *)
let run_loop
      ~(config : runtime_config)
      ~(trading : Dio_strategies.Strategy_common.trading_config list)
      ~(on_publish : string list -> decision list -> unit)
      ()
  : unit Lwt.t
  =
  let tasks, unsupported =
    Oracle_tasks.resolve_tasks
      ~symbol:""
      ~exchange:""
      ~exchange_explicit:false
      ~trading
      ~offline:false
  in
  List.iter
    (fun (sym, exch) ->
       Logging.warn_f
         ~section
         "%s/%s has no capital-survival adapter; it will receive no decisions"
         exch
         sym)
    unsupported;
  (* Warm fees and histories in the background; assets without usable data
     simply receive no decision until the first refresh lands (domains keep
     their startup gate closed - they place nothing before real values). *)
  Lwt.async (fun () ->
    Lwt_list.iter_s
      (fun (t : Oracle_tasks.task) ->
         if Option.is_none t.config.maker_fee
         then
           Lwt.catch
             (fun () ->
                Oracle_fees.resolved_fees
                  ~exchange:t.exchange
                  ~symbol:t.symbol
                  ~testnet:t.config.testnet
                >|= fun _ -> ())
             (fun _ -> Lwt.return ())
         else Lwt.return ())
      tasks
    >>= fun () -> refresh_loop ~offline:false ~config ~tasks);
  let rec loop () =
    if is_stopped ()
    then (
      Logging.info ~section "oracle runtime stopped";
      Lwt.return ())
    else
      run_pass ~config ~tasks ~on_publish
      >>= fun () ->
      wait_until
        ~deadline:(Unix.gettimeofday () +. (Float.max 1.0 config.refresh_seconds /. 4.0))
        ~generation:(Atomic.get pass_requested)
        ()
      >>= loop
  in
  loop ()
;;
