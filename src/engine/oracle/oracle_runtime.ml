(** Live current price: in-process top-of-book when sane (within +/-30% of the last bar
    close), else the close itself. Zero network. *)
let live_buy_anchor ~(exchange : string) ~(symbol : string) ~(fallback : float) =
  let band = 0.30 in
  let sane price =
    fallback > 0.0 && price > 0.0 && Float.abs (price -. fallback) /. fallback <= band
  in
  match Exchange.Registry.get exchange with
  | None -> fallback
  | Some (module Ex) ->
    (match Ex.get_top_of_book ~symbol with
     | Some (bid, _, _, _) when sane bid -> bid
     | Some (_, _, ask, _) when sane ask -> ask
     | _ -> fallback)
;;

(** Base/quote parts of a "BASE/QUOTE" symbol (whole string when no slash). *)
let split_symbol (symbol : string) : string * string =
  match String.index_opt symbol '/' with
  | None -> symbol, "USD"
  | Some i ->
    String.sub symbol 0 i, String.sub symbol (i + 1) (String.length symbol - i - 1)
;;

(** Whether one asset currently has a resting buy order on exchange. Zero network. *)
let has_resting_buy ~(exchange : string) ~(symbol : string) : bool =
  match Exchange.Registry.get exchange with
  | None -> false
  | Some (module Ex) ->
    Ex.fold_open_orders ~symbol ~init:false ~f:(fun acc (o : Exchange.Types.open_order) ->
      acc || (o.side = Exchange.Types.Buy && o.remaining_qty > 0.0))
;;

(** Base tied in resting sells for one asset (remaining qty sum). *)
let resting_sell_base ~(exchange : string) ~(symbol : string) : float =
  match Exchange.Registry.get exchange with
  | None -> 0.0
  | Some (module Ex) ->
    Ex.fold_open_orders ~symbol ~init:0.0 ~f:(fun acc (o : Exchange.Types.open_order) ->
      if o.side = Exchange.Types.Sell && o.remaining_qty > 0.0
      then acc +. o.remaining_qty
      else acc)
;;

(** One traversal of an asset's open orders yielding all quantities the pass needs:
    resting-buy existence, quote committed to resting buys, and base tied in resting
    sells. One pass instead of three [fold_open_orders] walks. *)
let open_orders_summary ~(exchange : string) ~(symbol : string) : bool * float * float =
  match Exchange.Registry.get exchange with
  | None -> false, 0.0, 0.0
  | Some (module Ex) ->
    Ex.fold_open_orders
      ~symbol
      ~init:(false, 0.0, 0.0)
      ~f:(fun (has_buy, committed, sell_base) (o : Exchange.Types.open_order) ->
        if o.remaining_qty <= 0.0
        then has_buy, committed, sell_base
        else (
          match o.side with
          | Exchange.Types.Buy ->
            let px =
              match o.limit_price with
              | Some p -> p
              | None -> 0.0
            in
            true, committed +. (o.remaining_qty *. px), sell_base
          | Exchange.Types.Sell -> has_buy, committed, sell_base +. o.remaining_qty))
;;

(* ------------------------------------------------------------------ *)
(* Pool events (fills / cancels move availability in process) *)
(* ------------------------------------------------------------------ *)

type pool_event =
  { pe_account : string (** Account key. *)
  ; pe_delta_quote : float
  ; pe_delta_base : float
  ; pe_base_asset : string
  ; pe_cause : string
  ; pe_quote_updated_at : float
  (** The account's tradeable-figure timestamp for its quote asset at the moment the event
      was recorded (0.0 = the venue cannot report one). *)
  ; pe_event_time : float
  (** The venue's own time for the execution report (0.0 = the feed could only stamp its
      own arrival, which cannot prove the figure has incorporated the event). *)
  }

let event_mutex = Mutex.create ()
let event_queue_cap = 16_384

(** Per-account cap on unconfirmed deltas. Retirement now requires venue evidence - the
    figure moving to or past the event time - so an account whose venue reports neither
    side would otherwise accumulate deltas for the life of the process. Such deltas can
    never be resolved either way, and the oldest are dropped, mirroring [event_queue_cap]. *)
let pending_per_account_cap = 256

let event_queue : pool_event Queue.t = Queue.create ()
let pending_pool_adjustments : (string, pool_event list) Hashtbl.t = Hashtbl.create 8

(** Venue time at which [exchange]'s tradeable figure for [asset] last moved, or 0.0 when
    the venue does not track it. Covers every input to that figure, holds included, so
    comparing it against an event's recorded value answers "has the venue incorporated
    this fill or cancel?". Lock-free atomic reads only; no clock. *)
let tradeable_updated_at ~(exchange : string) ~(asset : string) : float =
  match Exchange.Registry.get exchange with
  | None -> 0.0
  | Some (module Ex) -> Option.value (Ex.get_balance_updated_at ~asset) ~default:0.0
;;

let account_key_of ~(exchange : string) ~(testnet : bool) ~(quote : string) : string =
  Printf.sprintf "%s|%s|%s" exchange (string_of_bool testnet) quote
;;

(** [true] when the venue's figure has already moved to or past the event at the moment we
    are about to record it, so the snapshot the oracle reads already includes the fill or
    cancel and no delta should be queued at all. *)
let already_incorporated ~(event_time : float) ~(quote_updated_at : float) =
  event_time > 0.0 && quote_updated_at >= event_time
;;

let enqueue_pool_event
  account
  ~delta_quote
  ~delta_base
  ~base_asset
  ~quote_updated_at
  ~event_time
  cause
  =
  if already_incorporated ~event_time ~quote_updated_at
  then ()
  else (
    Mutex.lock event_mutex;
    if Queue.length event_queue >= event_queue_cap
    then (
      Logging.warn_f ~section "pool event queue full; dropping oldest events";
      Queue.clear event_queue);
    Queue.push
      { pe_account = account
      ; pe_delta_quote = delta_quote
      ; pe_delta_base = delta_base
      ; pe_base_asset = base_asset
      ; pe_cause = cause
      ; pe_quote_updated_at = quote_updated_at
      ; pe_event_time = event_time
      }
      event_queue;
    Mutex.unlock event_mutex)
;;

(** Moves queued events into the per-account pending adjustment table. Called at the top
    of every pass - the pass itself stays lock-free. *)
let drain_pool_events () =
  Mutex.lock event_mutex;
  let events = Queue.fold (fun acc e -> e :: acc) [] event_queue in
  Queue.clear event_queue;
  Mutex.unlock event_mutex;
  List.iter
    (fun e ->
      let l =
        Hashtbl.find_opt pending_pool_adjustments e.pe_account |> Option.value ~default:[]
      in
      let l = e :: l in
      Hashtbl.replace
        pending_pool_adjustments
        e.pe_account
        (if List.length l > pending_per_account_cap
         then List.filteri (fun i _ -> i < pending_per_account_cap) l
         else l))
    (List.rev events)
;;

(** A fill returns/consumes quote AND base: a buy consumes value+fee of quote and credits
    filled base; a sell credits value-fee and debits the sold base.

    The pass loop drains the venue execution rings and calls these directly; no payload,
    lock, or allocation crosses a producer thread. *)
let apply_fill
  ~(exchange : string)
  ~(symbol : string)
  ~(testnet : bool)
  ~(side : Exchange.Types.order_side)
  ~(filled_qty : float)
  ~(avg_price : float)
  ~(fee : float)
  ~(event_time : float)
  =
  let base, quote = split_symbol symbol in
  let value = filled_qty *. avg_price in
  let dq, db =
    match side with
    | Exchange.Types.Buy -> -.(value +. Float.max 0.0 fee), filled_qty
    | Exchange.Types.Sell -> value -. Float.max 0.0 fee, -.filled_qty
  in
  enqueue_pool_event
    (account_key_of ~exchange ~testnet ~quote)
    ~delta_quote:dq
    ~delta_base:db
    ~base_asset:base
    ~quote_updated_at:(tradeable_updated_at ~exchange ~asset:quote)
    ~event_time
    "fill"
;;

(** A canceled/rejected/expired order releases committed capital: a canceled BUY returns
    its remaining committed value (remaining_qty x limit price); a canceled sell releases
    base inventory, never quote. *)
let apply_order_cancel
  ~(exchange : string)
  ~(symbol : string)
  ~(testnet : bool)
  ~(side : Exchange.Types.order_side)
  ~(value : float)
  ~(event_time : float)
  =
  let base, quote = split_symbol symbol in
  if side = Exchange.Types.Buy
  then
    enqueue_pool_event
      (account_key_of ~exchange ~testnet ~quote)
      ~delta_quote:(Float.max 0.0 value)
      ~delta_base:0.0
      ~base_asset:base
      ~quote_updated_at:(tradeable_updated_at ~exchange ~asset:quote)
      ~event_time
      "order_cancel"
;;

(** Absolute read position per [(exchange, symbol)] for the execution-ring drain. *)
let exec_cursors : (string * string, int) Hashtbl.t = Hashtbl.create 16

(** Start every cursor at the venue ring's current end. Events that happened before the
    oracle started are already represented by the live balance store; replaying them would
    double-count on a supervisor restart. Events after this point are applied by the first
    pass (and [confirmed] drops any the balance store already reflects). *)
let init_exec_cursors (tasks : Oracle_tasks.task list) =
  List.iter
    (fun (t : Oracle_tasks.task) ->
      match Exchange.Registry.get t.exchange with
      | None -> ()
      | Some (module Ex) ->
        Hashtbl.replace
          exec_cursors
          (t.exchange, t.symbol)
          (Ex.get_execution_feed_position ~symbol:t.symbol))
    tasks
;;

let maker_fee_of ~exchange ~symbol =
  match Oracle_fees.cached_fees ~exchange ~symbol with
  | Some (m, _) -> Float.max 0.0 m
  | None -> Float.max 0.0 (fst (Oracle_fees.venue_default_fees exchange symbol))
;;

(** Last cumulative filled quantity applied per order. Partial fills arrive with a
    cumulative figure, so applying the raw event would double-count every earlier partial
    once the terminal fill lands. Only the delta since the previous event is a pool move. *)
let exec_fill_cum : (string, float) Hashtbl.t = Hashtbl.create 64

let apply_fill_delta
  ?fee_rate
  ~exchange
  ~symbol
  ~testnet
  ~(e : Exchange.Types.execution_event)
  ()
  =
  let prev = Option.value (Hashtbl.find_opt exec_fill_cum e.order_id) ~default:0.0 in
  let delta_qty = Float.max 0.0 (e.filled_qty -. prev) in
  if delta_qty > 0.0
  then (
    let fee_rate =
      match fee_rate with
      | Some f -> f
      | None -> maker_fee_of ~exchange ~symbol
    in
    apply_fill
      ~exchange
      ~symbol
      ~testnet
      ~side:e.side
      ~filled_qty:delta_qty
      ~avg_price:e.avg_price
      ~fee:(fee_rate *. delta_qty *. e.avg_price)
      ~event_time:e.venue_time);
  match e.order_status with
  | Exchange.Types.Filled -> Hashtbl.remove exec_fill_cum e.order_id
  | _ -> Hashtbl.replace exec_fill_cum e.order_id e.filled_qty
;;

(** Drain every task's execution ring. Each reader keeps its own absolute cursor, so the
    domain and the oracle can consume the same lock-free ring independently. *)
let drain_execution_events (tasks : Oracle_tasks.task list) =
  List.iter
    (fun (t : Oracle_tasks.task) ->
      match Exchange.Registry.get t.exchange with
      | None -> ()
      | Some (module Ex) ->
        let key = t.exchange, t.symbol in
        let start = Option.value (Hashtbl.find_opt exec_cursors key) ~default:0 in
        let next =
          Ex.iter_execution_events
            ~symbol:t.symbol
            ~start_pos:start
            (fun (e : Exchange.Types.execution_event) ->
               match e.order_status with
               | Exchange.Types.Filled | Exchange.Types.PartiallyFilled ->
                 apply_fill_delta
                   ~exchange:t.exchange
                   ~symbol:t.symbol
                   ~testnet:t.config.testnet
                   ~e
                   ()
               | Exchange.Types.Canceled
               | Exchange.Types.Rejected
               | Exchange.Types.Expired ->
                 Hashtbl.remove exec_fill_cum e.order_id;
                 apply_order_cancel
                   ~exchange:t.exchange
                   ~symbol:t.symbol
                   ~testnet:t.config.testnet
                   ~side:e.side
                   ~value:(e.remaining_qty *. Option.value e.limit_price ~default:0.0)
                   ~event_time:e.venue_time
               | Exchange.Types.Pending | Exchange.Types.New | Exchange.Types.Unknown _ ->
                 ())
        in
        Hashtbl.replace exec_cursors key next)
    tasks
;;

(** A delta is redundant once the venue's tradeable figure for the account's quote asset
    has moved to or past the venue's own time for the event: the figure then demonstrably
    incorporates the fill or cancel.

    [pe_event_time] is the venue's execution time (0.0 when the feed could only stamp its
    own arrival, which cannot prove anything and is therefore never substituted).
    Comparing the figure's timestamp against it - rather than against the value the figure
    had when we recorded the event - is what closes the feed-ordering race: when the
    balance feed delivers first, the figure has already moved past the event, so the delta
    is dropped instead of being layered on top of a snapshot that already contains it.

    Both sides are venue-reported absolute times compared against each other, so this
    needs no clock read. With no venue time (0.0) we fall back to "has the figure moved
    since we recorded the event", the best available signal there. *)
let confirmed (e : pool_event) ~(quote_updated_at : float) =
  if e.pe_event_time > 0.0
  then quote_updated_at >= e.pe_event_time
  else e.pe_quote_updated_at > 0.0 && quote_updated_at > e.pe_quote_updated_at
;;

(** Pending quote deltas to overlay on the account's snapshot, plus the per-event list for
    callers that also need base deltas. Confirmed deltas are dropped in passing. *)
let pending_deltas account ~(quote_updated_at : float) =
  match Hashtbl.find_opt pending_pool_adjustments account with
  | None -> 0.0, []
  | Some events ->
    let kept, dq =
      List.fold_left
        (fun (kept, dq) (e : pool_event) ->
          if confirmed e ~quote_updated_at
          then kept, dq
          else e :: kept, dq +. e.pe_delta_quote)
        ([], 0.0)
        events
    in
    dq, kept
;;

let prune_pending account ~(quote_updated_at : float) =
  match Hashtbl.find_opt pending_pool_adjustments account with
  | None -> ()
  | Some events ->
    let kept =
      List.filter (fun (e : pool_event) -> not (confirmed e ~quote_updated_at)) events
    in
    if kept = []
    then Hashtbl.remove pending_pool_adjustments account
    else Hashtbl.replace pending_pool_adjustments account kept
;;

