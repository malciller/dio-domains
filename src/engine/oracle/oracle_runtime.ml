let history_cache : (string * string, Oracle_types.series) Hashtbl.t = Hashtbl.create 16

(** References derived from each asset's bars, invalidated when the merged history
    actually changes ([refresh_asset_history] below) or when the configured lookback
    differs from the one cached. The O(history_len) reference scan is otherwise invariant
    across passes. Stores the window it was computed with. *)
let references_cache : (string * string, int * Oracle_core.references) Hashtbl.t =
  Hashtbl.create 16
;;

let history_of_cached ~(offline : bool) ~(exchange : string) ~(symbol : string)
  : Oracle_types.series Lwt.t
  =
  match Hashtbl.find_opt history_cache (exchange, symbol) with
  | Some s -> Lwt.return s
  | None -> Oracle_pipeline.history_of ~offline ~exchange ~symbol
;;

let same_bars (a : Oracle_types.bar array) (b : Oracle_types.bar array) =
  Array.length a = Array.length b
  &&
  let rec go i =
    i < 0
    || ((let (x : Oracle_types.bar) = a.(i) in
         let (y : Oracle_types.bar) = b.(i) in
         String.equal x.date y.date
         && Float.abs (x.close -. y.close) <= 1e-12 *. Float.max 1.0 (Float.abs x.close)
         && Float.abs (x.high -. y.high) <= 1e-12 *. Float.max 1.0 (Float.abs x.high)
         && Float.abs (x.low -. y.low) <= 1e-12 *. Float.max 1.0 (Float.abs x.low))
        && go (i - 1))
  in
  go (Array.length a - 1)
;;

(** Refresh one asset's merged all-time history into the cache. Returns whether the bars
    actually changed. Network work - background only. *)
let refresh_asset_history ~(offline : bool) ~(exchange : string) ~(symbol : string)
  : bool Lwt.t
  =
  Lwt.catch
    (fun () ->
      Oracle_pipeline.history_of ~offline ~exchange ~symbol
      >|= fun series ->
      (* Keep the previous series when the bars are unchanged. Replacing it on every
         periodic refresh retained a fresh copy of every bar array (and its date strings)
         per refresh even though nothing had changed - history only moves once a day. The
         new series is left to the GC; the cached one stays stable until a bar actually
         changes. *)
      match Hashtbl.find_opt history_cache (exchange, symbol) with
      | Some prev when same_bars prev.bars series.bars -> false
      | _ ->
        Hashtbl.replace history_cache (exchange, symbol) series;
        Hashtbl.remove references_cache (exchange, symbol);
        true)
    (fun exn ->
      Logging.warn_f
        ~section
        "history refresh failed for %s/%s: %s"
        exchange
        symbol
        (Printexc.to_string exn);
      Lwt.return false)
;;

