(** A venue account: pools never cross these. *)
type account =
  { a_exchange : string
  ; a_testnet : bool
  ; a_quote : string
  }

let account_id (a : account) =
  account_key_of ~exchange:a.a_exchange ~testnet:a.a_testnet ~quote:a.a_quote
;;

let account_of_task (t : Oracle_tasks.task) : account =
  let _, quote = split_symbol t.symbol in
  { a_exchange = t.exchange; a_testnet = t.config.testnet; a_quote = quote }
;;

let same_account x y =
  String.equal x.a_exchange y.a_exchange
  && x.a_testnet = y.a_testnet
  && String.equal x.a_quote y.a_quote
;;

(** Tasks grouped by venue account, preserving config.json order (priority order within
    each account). *)
let group_by_account (tasks : Oracle_tasks.task list)
  : (account * Oracle_tasks.task list) list
  =
  let accounts = ref [] in
  List.iter
    (fun (task : Oracle_tasks.task) ->
      let account = account_of_task task in
      if not (List.exists (same_account account) !accounts)
      then accounts := account :: !accounts)
    tasks;
  let accounts = List.rev !accounts in
  List.map
    (fun account ->
      ( account
      , List.filter
          (fun (task : Oracle_tasks.task) -> same_account account (account_of_task task))
          tasks ))
    accounts
;;

(** Last known balance snapshots per account id, warmed by the background refresher and
    the initial pass. *)
type pool_state =
  { snap : Oracle_balances.snapshot
  ; fetched_at : float
  }

let pool_cache : (string, pool_state) Hashtbl.t = Hashtbl.create 8
let clear_pool_cache () = Hashtbl.reset pool_cache

(** Fetch balances for one task (live store first, REST fallback) into the pool cache.
    Network - called from the refresher and startup only. *)
let refresh_balance_of_task (task : Oracle_tasks.task) : unit Lwt.t =
  let account = account_of_task task in
  let id = account_id account in
  Lwt.catch
    (fun () ->
      Oracle_balances.fetch_task_live task
      >|= function
      | Error error ->
        Logging.warn_f ~section "balance refresh failed for %s: %s" id error
      | Ok snapshot ->
        Hashtbl.replace
          pool_cache
          id
          { snap = snapshot; fetched_at = Unix.gettimeofday () })
    (fun exn ->
      Logging.warn_f
        ~section
        "balance refresh failed for %s: %s"
        id
        (Printexc.to_string exn);
      Lwt.return ())
;;

(** Per-account balance view for one pass: live-store snapshot when present, else the
    cached snapshot, plus the venue time the account's quote-asset tradeable figure last
    moved - the reference a pending delta is judged redundant against. Built once per
    account rather than 2-4 times per asset (each rebuild is O(balances x symbols)). *)
type account_snapshot =
  { acs_snap : Oracle_balances.snapshot
  ; acs_quote_updated_at : float
  }

let account_snapshot_of (a : account) : account_snapshot option =
  let id = account_id a in
  let quote_updated_at = tradeable_updated_at ~exchange:a.a_exchange ~asset:a.a_quote in
  let acs_of snap = { acs_snap = snap; acs_quote_updated_at = quote_updated_at } in
  match
    Oracle_balances.snapshot_of_live_store ~exchange:a.a_exchange ~testnet:a.a_testnet ()
  with
  | Some snap -> Some (acs_of snap)
  | None -> Option.map (fun p -> acs_of p.snap) (Hashtbl.find_opt pool_cache id)
;;

(** Available quote within a hoisted snapshot: live/cached balance plus the in-process
    pending deltas the venue has not yet incorporated. Zero network, zero clock. *)
let available_quote_in (a : account) (acs : account_snapshot) : float =
  let id = account_id a in
  let quote_updated_at = acs.acs_quote_updated_at in
  let dq, pending = pending_deltas id ~quote_updated_at in
  if pending <> [] then prune_pending id ~quote_updated_at;
  let raw =
    Float.max 0.0 (Oracle_balances.available_quote acs.acs_snap ~quote:a.a_quote +. dq)
  in
  (* Senior overlay reservations are not available to the grid. Subtracting them here
     keeps the capital oracle's sizing pool aligned with the execution-side
     [Capital_reservation.available]. With no overlay the total is 0 and this is a no-op. *)
  let reserved = Dio_exchange.Capital_reservation.get_total ~exchange:a.a_exchange in
  Float.max 0.0 (raw -. reserved)
;;

(** Available base for one symbol within a hoisted snapshot (same sources), minus nothing:
    reserved_base is excluded upstream by the execution layer's available_trading_balance.
    Resting sells are subtracted separately. *)
let available_base_in (a : account) ~(symbol : string) (acs : account_snapshot) : float =
  let id = account_id a in
  let quote_updated_at = acs.acs_quote_updated_at in
  let base, _ = split_symbol symbol in
  let _, pending = pending_deltas id ~quote_updated_at in
  let db =
    List.fold_left
      (fun acc (e : pool_event) ->
        if String.equal e.pe_base_asset base then acc +. e.pe_delta_base else acc)
      0.0
      pending
  in
  if pending <> [] then prune_pending id ~quote_updated_at;
  Float.max 0.0 (Oracle_balances.available_asset acs.acs_snap ~asset:base +. db)
;;

