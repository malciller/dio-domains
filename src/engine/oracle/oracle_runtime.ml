(** Live current price: in-process top-of-book when sane (within +/-30% of
    the last bar close), else the close itself. Zero network. *)
let live_buy_anchor ~(exchange : string) ~(symbol : string) ~(fallback : float) =
  let band = 0.30 in
  let sane price =
    fallback > 0.0 && price > 0.0 && Float.abs (price -. fallback) /. fallback <= band
  in
  match Exchange.Registry.get exchange with
  | None -> fallback
  | Some (module Ex) ->
    (match Ex.get_top_of_book ~symbol with
     | Some (bid, _, _, _) when sane bid -> bid
     | Some (_, _, ask, _) when sane ask -> ask
     | _ -> fallback)
;;

(** Base/quote parts of a "BASE/QUOTE" symbol (whole string when no slash). *)
let split_symbol (symbol : string) : string * string =
  match String.index_opt symbol '/' with
  | None -> symbol, "USD"
  | Some i ->
    String.sub symbol 0 i, String.sub symbol (i + 1) (String.length symbol - i - 1)
;;

(** Quote tied in resting buys for one asset: fold of the in-process open
    order registry (remaining qty x limit price). Zero network. *)
let committed_buy_value ~(exchange : string) ~(symbol : string) : float =
  match Exchange.Registry.get exchange with
  | None -> 0.0
  | Some (module Ex) ->
    Ex.fold_open_orders ~symbol ~init:0.0 ~f:(fun acc (o : Exchange.Types.open_order) ->
      if o.side = Exchange.Types.Buy && o.remaining_qty > 0.0
      then
        acc
        +. (o.remaining_qty
            *.
            match o.limit_price with
            | Some p -> p
            | None -> 0.0)
      else acc)
;;

(** Whether one asset currently has a resting buy order on exchange. Zero network. *)
let has_resting_buy ~(exchange : string) ~(symbol : string) : bool =
  match Exchange.Registry.get exchange with
  | None -> false
  | Some (module Ex) ->
    Ex.fold_open_orders ~symbol ~init:false ~f:(fun acc (o : Exchange.Types.open_order) ->
      acc || (o.side = Exchange.Types.Buy && o.remaining_qty > 0.0))
;;

(** Base tied in resting sells for one asset (remaining qty sum). *)
let resting_sell_base ~(exchange : string) ~(symbol : string) : float =
  match Exchange.Registry.get exchange with
  | None -> 0.0
  | Some (module Ex) ->
    Ex.fold_open_orders ~symbol ~init:0.0 ~f:(fun acc (o : Exchange.Types.open_order) ->
      if o.side = Exchange.Types.Sell && o.remaining_qty > 0.0
      then acc +. o.remaining_qty
      else acc)
;;

(* ------------------------------------------------------------------ *)
(* Pool events (fills / cancels move availability in process)          *)
(* ------------------------------------------------------------------ *)

type pool_event =
  { pe_account : string (** Account key. *)
  ; pe_delta_quote : float
  ; pe_delta_base : float
  ; pe_base_asset : string
  ; pe_cause : string
  ; pe_baseline : int (** Balance epoch the delta was measured against. *)
  }

let event_mutex = Mutex.create ()
let event_queue_cap = 16_384
let event_queue : pool_event Queue.t = Queue.create ()
let pending_pool_adjustments : (string, pool_event list) Hashtbl.t = Hashtbl.create 8
let balance_epoch : int Atomic.t = Atomic.make 0

let account_key_of ~(exchange : string) ~(testnet : bool) ~(quote : string) : string =
  Printf.sprintf "%s|%s|%s" exchange (string_of_bool testnet) quote
;;

let enqueue_pool_event account ~delta_quote ~delta_base ~base_asset cause =
  Mutex.lock event_mutex;
  if Queue.length event_queue >= event_queue_cap
  then (
    Logging.warn_f ~section "pool event queue full; dropping oldest events";
    Queue.clear event_queue);
  Queue.push
    { pe_account = account
    ; pe_delta_quote = delta_quote
    ; pe_delta_base = delta_base
    ; pe_base_asset = base_asset
    ; pe_cause = cause
    ; pe_baseline = Atomic.get balance_epoch
    }
    event_queue;
  Mutex.unlock event_mutex
;;

(** Moves queued events into the per-account pending adjustment table.
    Called at the top of every pass - the pass itself stays lock-free. *)
let drain_pool_events () =
  Mutex.lock event_mutex;
  let events = Queue.fold (fun acc e -> e :: acc) [] event_queue in
  Queue.clear event_queue;
  Mutex.unlock event_mutex;
  List.iter
    (fun e ->
       let l =
         Hashtbl.find_opt pending_pool_adjustments e.pe_account
         |> Option.value ~default:[]
       in
       Hashtbl.replace pending_pool_adjustments e.pe_account (e :: l))
    (List.rev events)
;;

(** A fill returns/consumes quote AND base: a buy consumes value+fee of
    quote and credits filled base; a sell credits value-fee and debits the
    sold base. Wakes the runtime - deltas are applied in process, so the
    decision never waits on a network balance refresh. *)
let notify_fill
      ~(exchange : string)
      ~(symbol : string)
      ~(testnet : bool)
      ~(side : Exchange.Types.order_side)
      ~(filled_qty : float)
      ~(avg_price : float)
      ~(fee : float)
  =
  let base, quote = split_symbol symbol in
  let value = filled_qty *. avg_price in
  let dq, db =
    match side with
    | Exchange.Types.Buy -> -.(value +. Float.max 0.0 fee), filled_qty
    | Exchange.Types.Sell -> value -. Float.max 0.0 fee, -.filled_qty
  in
  enqueue_pool_event
    (account_key_of ~exchange ~testnet ~quote)
    ~delta_quote:dq
    ~delta_base:db
    ~base_asset:base
    "fill";
  request_pass ()
;;

(** A canceled/rejected/expired order releases committed capital: a canceled
    BUY returns its remaining committed value (remaining_qty x limit price);
    a canceled sell releases base inventory, never quote. Wakes the runtime. *)
let notify_order_cancel
      ~(exchange : string)
      ~(symbol : string)
      ~(testnet : bool)
      ~(side : Exchange.Types.order_side)
      ~(value : float)
  =
  let base, quote = split_symbol symbol in
  if side = Exchange.Types.Buy
  then
    enqueue_pool_event
      (account_key_of ~exchange ~testnet ~quote)
      ~delta_quote:(Float.max 0.0 value)
      ~delta_base:0.0
      ~base_asset:base
      "order_cancel";
  request_pass ()
;;

(** Pending quote/base deltas valid for [epoch]: measured at the current
    balance epoch (a fresher authoritative snapshot already includes them -
    older deltas are dropped, never double-counted). *)
let pending_deltas account epoch =
  match Hashtbl.find_opt pending_pool_adjustments account with
  | None -> 0.0, []
  | Some events ->
    let kept, dq =
      List.fold_left
        (fun (kept, dq) (e : pool_event) ->
           if e.pe_baseline = epoch then e :: kept, dq +. e.pe_delta_quote else kept, dq)
        ([], 0.0)
        events
    in
    dq, kept
;;

let prune_pending account epoch =
  match Hashtbl.find_opt pending_pool_adjustments account with
  | None -> ()
  | Some events ->
    let kept = List.filter (fun (e : pool_event) -> e.pe_baseline = epoch) events in
    if kept = []
    then Hashtbl.remove pending_pool_adjustments account
    else Hashtbl.replace pending_pool_adjustments account kept
;;

