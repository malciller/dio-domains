(** Refreshes histories + balances for every task once (network). Sets [materialized]
    after the first attempt and wakes the runtime when any history changed or balances
    arrived. *)
let refresh_once ~(offline : bool) ~(tasks : Oracle_tasks.task list) : unit Lwt.t =
  let started = Mtime_clock.now_ns () in
  Lwt_list.iter_s
    (fun (t : Oracle_tasks.task) ->
      refresh_asset_history ~offline ~exchange:t.exchange ~symbol:t.symbol
      >>= fun changed ->
      if changed then Atomic.set history_changed true;
      Lwt.return ())
    tasks
  >>= fun () ->
  (* [Oracle_fetch.fetch_cache] is a per-pass dedup cache, but it was never cleared: the
     first fetch's series stayed cached forever, so the venue history never picked up a
     new daily bar after startup. Clear it now that every asset has been refreshed; the
     durable copy still lives in [history_cache] and on disk. *)
  Oracle_fetch.clear_cache ();
  let t_bal = Mtime_clock.now_ns () in
  let accounts = group_by_account tasks |> List.map fst in
  Lwt_list.iter_s
    (fun account ->
      match
        List.find_opt
          (fun (t : Oracle_tasks.task) -> same_account account (account_of_task t))
          tasks
      with
      | None -> Lwt.return ()
      | Some task -> refresh_balance_of_task task)
    accounts
  >>= fun () ->
  Latency_profiler.record (Lazy.force engine_profs).prof_balance (span_from t_bal);
  Atomic.incr refresh_generation;
  Atomic.set materialized_ref (Some { m_epoch = Atomic.get refresh_generation });
  Lwt_condition.broadcast materialized_condition ();
  Latency_profiler.record (Lazy.force engine_profs).prof_fetch (span_from started);
  let _ = Latency_profiler.snapshot_and_reset (Lazy.force engine_profs).prof_balance in
  let _ = Latency_profiler.snapshot_and_reset (Lazy.force engine_profs).prof_fetch in
  request_pass ();
  Lwt.return ()
;;

(** Periodic history/balance refresh.

    This loop must NOT wait on [pass_requested]: that counter is bumped by every order,
    fill, balance and book event, so waiting on it makes [refresh_once] run on every
    market event instead of every [refresh_seconds]. Each run re-reads and re-parses every
    asset's full all-time history, which is a multi-megabyte allocation burst; at event
    frequency it both burns CPU and keeps the previous series' parse trees reachable
    through the never-resolving bind chain.

    Each iteration is spawned independently ([Lwt.async loop]) so the completed
    iteration's promise chain can be collected rather than being retained by the recursive
    [>>=] chain. The initial refresh is still performed once by {!run_loop} before this
    loop starts. *)
let refresh_loop
  ~(offline : bool)
  ~(config : runtime_config)
  ~(tasks : Oracle_tasks.task list)
  : unit Lwt.t
  =
  let interval =
    if config.refresh_seconds > 0.0 then config.refresh_seconds else 3600.0
  in
  let rec loop () =
    if is_stopped ()
    then Lwt.return ()
    else
      Lwt_unix.sleep interval
      >>= fun () ->
      if is_stopped ()
      then Lwt.return ()
      else
        refresh_once ~offline ~tasks
        >>= fun () ->
        (* Spawn the next iteration independently to sever the Lwt.bind chain. *)
        Lwt.async loop;
        Lwt.return ()
  in
  loop ()
;;

(* ------------------------------------------------------------------ *)
(* Main loop *)
(* ------------------------------------------------------------------ *)

(** Runs the oracle until shutdown: initial background refresh, then an event-driven pass
    loop. Venue state transitions (execution events, balance changes, open-order/claim
    changes) ring the doorbell; passes coalesce a burst into one re-resolve. There is no
    control-path timeout - the loop blocks on the doorbell. Returns when [shutdown] is
    requested. *)
let run_loop
  ~(config : runtime_config)
  ~(trading : Dio_strategies.Strategy_common.trading_config list)
  ~(on_publish : string list -> decision list -> unit)
  ()
  : unit Lwt.t
  =
  Concurrency.Oracle_wakeup.set_wake request_pass;
  let tasks, unsupported =
    Oracle_tasks.resolve_tasks
      ~symbol:""
      ~exchange:""
      ~exchange_explicit:false
      ~trading
      ~offline:false
  in
  init_exec_cursors tasks;
  List.iter
    (fun (sym, exch) ->
      Logging.warn_f
        ~section
        "%s/%s has no capital-survival adapter; it will receive no decisions"
        exch
        sym)
    unsupported;
  (* Warm fees and histories in the background; assets without usable data simply receive
     no decision until the first refresh lands (domains keep their startup gate closed -
     they place nothing before real values). *)
  Lwt.async (fun () ->
    Lwt_list.iter_s
      (fun (t : Oracle_tasks.task) ->
        if Option.is_none t.config.maker_fee
        then
          Lwt.catch
            (fun () ->
              Oracle_fees.resolved_fees
                ~exchange:t.exchange
                ~symbol:t.symbol
                ~testnet:t.config.testnet
              >|= fun _ -> ())
            (fun _ -> Lwt.return ())
        else Lwt.return ())
      tasks
    >>= fun () ->
    (* Do the first refresh now, not after [refresh_seconds]. The startup gate waits on
       [materialized_ref]; sleeping first withheld every grid order for the full refresh
       interval (five minutes by default). *)
    Lwt.catch
      (fun () -> refresh_once ~offline:false ~tasks)
      (fun exn ->
        Logging.error_f
          ~section
          "initial oracle refresh failed: %s"
          (Printexc.to_string exn);
        Lwt.return_unit)
    >>= fun () -> refresh_loop ~offline:false ~config ~tasks);
  (* The first pass must not run cold: refresh_once warms the account balance pool and
     sets [materialized_ref] on completion. Without this gate the very first pass can race
     the initial balance fetch, report "no balance data", and emit no decision for the
     account - which leaves those assets un-materialized and buying nothing until the next
     refresh (up to refresh_seconds). *)
  let rec wait_initial_refresh () =
    if Option.is_some (Atomic.get materialized_ref) || is_stopped ()
    then Lwt.return ()
    else (
      let w = Lwt_condition.wait materialized_condition in
      if Option.is_some (Atomic.get materialized_ref) || is_stopped ()
      then Lwt_condition.broadcast materialized_condition ();
      w >>= wait_initial_refresh)
  in
  wait_initial_refresh ()
  >>= fun () ->
  (* [run_loop]'s promise is held by the supervisor's [Lwt.pick] for the life of the
     oracle. A recursive [wait_event >>= loop] would therefore pin one Lwt Forward node
     per pass (the head stays reachable from the pick), growing the heap without bound.
     Each iteration is spawned independently and [finished] preserves the old contract: it
     resolves on shutdown or fails if an iteration raises. *)
  let finished, finished_u = Lwt.wait () in
  let finish_ok () = if Lwt.is_sleeping finished then Lwt.wakeup_later finished_u () in
  let finish_error exn =
    if Lwt.is_sleeping finished then Lwt.wakeup_later_exn finished_u exn
  in
  let rec loop () =
    if is_stopped ()
    then (
      Logging.info ~section "oracle runtime stopped";
      finish_ok ();
      Lwt.return_unit)
    else (
      (* Capture before the pass so a request landing mid-pass is consumed by the
         post-pass predicate recheck. *)
      let generation = Atomic.get pass_requested in
      Atomic.set pass_running true;
      Lwt.catch
        (fun () ->
          run_pass ~config ~tasks ~on_publish
          >>= fun () ->
          Atomic.set pass_running false;
          wait_event ~generation ()
          >>= fun () ->
          if is_stopped ()
          then (
            finish_ok ();
            Lwt.return_unit)
          else (
            Lwt.async loop;
            Lwt.return_unit))
        (fun exn ->
          Atomic.set pass_running false;
          finish_error exn;
          Lwt.return_unit))
  in
  Lwt.async loop;
  finished
;;
