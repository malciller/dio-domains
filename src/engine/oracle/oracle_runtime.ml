let string_of_regime = function
  | Oracle_core.Normal -> "normal"
  | Oracle_core.Floor_extension -> "floor extension"
  | Oracle_core.Unprecedented_lows -> "unprecedented lows"
;;

let string_of_branch = function
  | Oracle_core.Reachable -> "reachable"
  | Oracle_core.Surplus -> "surplus"
  | Oracle_core.Unreachable -> "unreachable"
;;

(** One venue re-resolve: walk the account's strategies in config order,
    size each against the entire remaining pool, deduct each funded need,
    and fire the cancellation cascade for starved strategies. *)
let run_account_pass
      ~(config : runtime_config)
      ~(account : account)
      ~(tasks : Oracle_tasks.task list)
  : decision list Lwt.t
  =
  match available_quote_now account with
  | None ->
    Logging.warn_f
      ~section
      "no balance data for %s yet; keeping last-known-good decisions"
      (account_id account);
    (* Keep prior decisions for this venue unchanged. *)
    Lwt.return
      (List.filter
         (fun (d : decision) ->
            List.exists
              (fun (t : Oracle_tasks.task) ->
                 String.equal t.exchange d.exchange && String.equal t.symbol d.symbol)
              tasks)
         (decisions ()))
  | Some pool ->
    let committed_venue_buys =
      List.fold_left
        (fun acc (t : Oracle_tasks.task) ->
           acc +. committed_buy_value ~exchange:t.exchange ~symbol:t.symbol)
        0.0
        tasks
    in
    let total_venue_quote = pool +. committed_venue_buys in
    let remaining = ref pool in
    let built
      : (Oracle_tasks.task * decision * float * float * Oracle_pipeline.outcome option) list ref
      =
      ref []
    in
    List.iteri
      (fun _idx (t : Oracle_tasks.task) ->
         let t_asset = Mtime_clock.now_ns () in
         let target_survival, min_active_dsurv, qty_cap_mult =
           effective_knobs ~config ~symbol:t.symbol
         in
         let qty_raw = float_of_string_opt t.config.qty |> Option.value ~default:0.0 in
         let bounds =
           { Oracle_core.qty = Float.max 1e-12 qty_raw
           ; qty_cap_mult = Float.max 1.0 qty_cap_mult
           ; gi_min = fst t.config.grid_interval
           ; gi_max = snd t.config.grid_interval
           }
         in
         (* No usable data yet: publish NOTHING for this asset rather than a
            garbage-zero inactive decision - a fabricated decision would open
            the domain's startup gate on values that were never computed.
            The asset joins the surface on the next pass, once the
            background refresh has delivered its history and balances. *)
         let skip_asset reason =
           record_asset_latency t.symbol (span_from t_asset) (fun () -> reason);
           Logging.debug_f
             ~section
             "%s/%s: %s; no decision published this pass"
             t.exchange
             t.symbol
             reason
         in
         match Hashtbl.find_opt history_cache (t.exchange, t.symbol) with
         | None -> skip_asset "history unavailable"
         | Some series ->
           let fallback_close =
             Option.value (Oracle_pipeline.current_price_of_series series) ~default:0.0
           in
           if fallback_close <= 0.0
           then skip_asset "history has no usable close"
           else (
             let current =
               live_buy_anchor
                 ~exchange:t.exchange
                 ~symbol:t.symbol
                 ~fallback:fallback_close
             in
             let resting_buy = has_resting_buy ~exchange:t.exchange ~symbol:t.symbol in
             let committed_buy =
               committed_buy_value ~exchange:t.exchange ~symbol:t.symbol
             in
             let effective_quote =
               if resting_buy then !remaining +. committed_buy else !remaining
             in
             let inputs : Oracle_pipeline.inputs =
               { exchange = t.exchange
               ; symbol = t.symbol
               ; bars = series.bars
               ; current_price = current
               ; available_quote = effective_quote
               ; sell_qty = 0.0
               ; bounds
               ; target_survival
               ; min_active_dsurv
               ; fees = fees_now t
               ; has_resting_buy = resting_buy
               }
             in
             match Oracle_pipeline.decide ~inputs with
             | None -> skip_asset "references unavailable"
             | Some o ->
               let base_avail =
                 Option.value (available_base_now account ~symbol:t.symbol) ~default:0.0
               in
               let sell_qty =
                 Oracle_pools.sell_qty_of
                   ~base_balance:base_avail
                   ~reserved_base:0.0
                   ~resting_sell_base:
                     (resting_sell_base ~exchange:t.exchange ~symbol:t.symbol)
               in
               let reason =
                 if o.decision.active
                 then ""
                 else if o.resolution.d_surv < min_active_dsurv
                 then
                   Printf.sprintf
                     "d_surv %.3f below min_active_dsurv %.3f"
                     o.resolution.d_surv
                     min_active_dsurv
                 else "awaiting reactivation: quote does not cover buy"
               in
               let d : decision =
                 { exchange = t.exchange
                 ; symbol = t.symbol
                 ; active = o.decision.active
                 ; grid_interval = o.decision.grid_interval
                 ; buy_qty = o.decision.buy_qty
                 ; sell_qty
                 ; max_drawdown_pct = o.refs.max_drawdown_pct
                 ; reason
                 ; d_surv = o.resolution.d_surv
                 ; regime = string_of_regime o.runway.regime
                 ; branch = string_of_branch o.resolution.branch
                 ; cancel_resting_buys = false
                 ; updated_at = Unix.gettimeofday ()
                 }
               in
               record_asset_latency
                 t.symbol
                 (span_from t_asset)
                 (fun () -> if d.active then "active" else "inactive");
               let need = d.buy_qty *. current in
               (* Funded strategies tie their next buy's quote; starved ones
                  pass capacity down untouched. Resting buys are already committed
                  in the venue pool, so only fresh active placements consume free quote. *)
               if d.active && (not resting_buy) && need <= !remaining +. 1e-9
               then remaining := !remaining -. need;
               built := (t, d, need, current, Some o) :: !built))
      tasks;
     let built_rev = List.rev !built in
     let key_of_task (t : Oracle_tasks.task) =
       Printf.sprintf "%s|%s" t.exchange t.symbol
     in
     let global_index (lt : Oracle_tasks.task) =
       let rec pos (k : int) (l : Oracle_tasks.task list) : int =
         match l with
         | [] -> k
         | x :: r ->
           if String.equal x.symbol lt.symbol && String.equal x.exchange lt.exchange
           then k
           else pos (k + 1) r
       in
       pos 0 tasks
     in
     (* Shared venue drawdown simulation: active strategies execute 1 order
        sequentially in priority order until venue quote capital is exhausted. *)
     let active_sim : Oracle_pools.sim_strategy list =
       List.filter_map
         (fun ((t, d, _, current, _) :
                 Oracle_tasks.task * decision * float * float * Oracle_pipeline.outcome option) ->
            if d.active
            then
              Some
                { Oracle_pools.id = key_of_task t
                ; priority = global_index t
                ; current
                ; grid_interval = d.grid_interval
                ; buy_qty = d.buy_qty
                ; maker_fee = (fees_now t).maker_fee
                }
            else None)
         built_rev
     in
     let sim_dsurvs =
       Oracle_pools.simulate_drawdown_survival ~total_quote:total_venue_quote active_sim
     in
     let built_rev =
       List.map
         (fun ((t, d, need, current, outcome) :
                 Oracle_tasks.task * decision * float * float * Oracle_pipeline.outcome option) ->
            let d_surv =
              if d.active
              then
                Option.value (List.assoc_opt (key_of_task t) sim_dsurvs) ~default:0.0
              else 0.0
            in
            (t, { d with d_surv }, need, current, outcome))
         built_rev
     in
     (* Cancellation cascade: a starved strategy (sizing met the survival
        requirement but its next buy does not fit) cancels lower-priority
        resting buys until its need fits - many lesser orders may be
        cancelled to satisfy one greater. The trigger's own orders are never
        cancelled. If no combination fits, resolution proceeds to the
        next-highest priority: nothing is flagged and capacity stays with the
        strategies that own it. Cancelled strategies re-evaluate on the
        cancel event this very pass triggers, resuming iff quote covers their
        buy. *)
     let rec drop n = function
       | [] -> []
       | _ :: r -> if n = 0 then r else drop (n - 1) r
     in
     let flagged : string list ref = ref [] in
     List.iteri
       (fun i
         ((t, d, need, _current, outcome) :
           Oracle_tasks.task * decision * float * float * Oracle_pipeline.outcome option) ->
          match outcome with
          | None -> ()
          | Some _ when d.active -> ()
          | Some o ->
            let eff_target_survival, _, _ =
              effective_knobs ~config ~symbol:t.symbol
            in
            if not (o.resolution.d_surv >= eff_target_survival)
            then ()
            else (
              let lower = drop (i + 1) tasks in
              let claims =
                lower
                |> List.filter (fun (lt : Oracle_tasks.task) ->
                  committed_buy_value ~exchange:lt.exchange ~symbol:lt.symbol > 0.0)
                |> List.map (fun (lt : Oracle_tasks.task) ->
                  (* Global config index: higher index = lower seniority, so
                     descending sort cancels the least senior first. *)
                  { Oracle_pools.id = key_of_task lt
                  ; priority = global_index lt
                  ; need_quote = 0.0
                  ; resting_buy_quote =
                      committed_buy_value ~exchange:lt.exchange ~symbol:lt.symbol
                  })
              in
              let plan =
                Oracle_pools.cascade
                  ~available:!remaining
                  ~need
                  ~trigger_id:(key_of_task t)
                  ~claims
              in
              if plan <> []
              then (
                flagged := List.rev_append plan !flagged;
                Logging.info_f
                  ~section
                  "cancellation cascade for %s/%s (need $%.2f vs $%.2f available): \
                   cancelling resting buys of [%s]"
                  t.exchange
                  t.symbol
                  need
                  !remaining
                  (String.concat ", " plan);
                ())
              else ()))
       built_rev;
     Lwt.return
       (List.map
          (fun ((_, d, _, _, _) :
                 Oracle_tasks.task * decision * float * float * Oracle_pipeline.outcome option) ->
             if List.mem (Printf.sprintf "%s|%s" d.exchange d.symbol) !flagged
             then { d with cancel_resting_buys = true }
             else d)
          built_rev)
;;

(** One full re-resolve across all venues. *)
let run_pass
      ~(config : runtime_config)
      ~(tasks : Oracle_tasks.task list)
      ~(on_publish : string list -> decision list -> unit)
  : unit Lwt.t
  =
  let started = Mtime_clock.now_ns () in
  let groups = group_by_account tasks in
  Lwt_list.fold_left_s
    (fun acc (account, tsks) ->
       run_account_pass ~config ~account ~tasks:tsks >|= fun ds -> ds :: acc)
    []
    groups
  >>= fun decision_lists ->
  publish ~on_publish (List.concat (List.rev decision_lists));
  Atomic.incr pass_count;
  let pass_span = span_from started in
  Latency_profiler.record (Lazy.force engine_profs).prof_pass pass_span;
  let _ = Latency_profiler.snapshot_and_reset (Lazy.force engine_profs).prof_pass in
  List.iter
    (fun (t : Oracle_tasks.task) ->
       ignore (Latency_profiler.snapshot_and_reset (asset_profiler_of t.symbol)))
    tasks;
  Logging.debug_f
    ~section
    "pass %d done (%d assets, %.1fms)"
    (Atomic.get pass_count)
    (List.length tasks)
    (Mtime.Span.to_float_ns pass_span /. 1e9 *. 1000.0);
  Lwt.return ()
;;

