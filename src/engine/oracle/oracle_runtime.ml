(** One asset's live trading decision, published for the domain workers.
    The contract is the four sizing/activity fields; the rest is
    observability. *)
type decision =
  { exchange : string
  ; symbol : string
  ; active : bool (** Run the strategy (place/amend buys); sells always run. *)
  ; reason : string (** Why inactive, when inactive (logs only). *)
  ; grid_interval : float (** Contract: resolved spacing in %. *)
  ; buy_qty : float (** Contract: buy order size in base units. *)
  ; sell_qty : float (** Contract: sell size from the venue base pool. *)
  ; max_drawdown_pct : float (** Historical lifetime peak-to-trough max drawdown. *)
  ; d_surv : float (** Replayed survival fraction (observability). *)
  ; regime : string (** Normal / floor extension / unprecedented lows. *)
  ; branch : string (** Search outcome: reachable / surplus / unreachable. *)
  ; cancel_resting_buys : bool
    (** Cancellation cascade action: a higher-priority strategy needs this
        asset's tied quote; the domain must cancel its resting buys so the
        capital returns to the pool. The resulting cancel event wakes the
        runtime and every cancelled strategy re-evaluates immediately,
        resuming iff quote covers its buy. *)
  ; updated_at : float (** Unix time of the pass that produced this. *)
  }

let decisions_ref : decision list Atomic.t = Atomic.make []

let decisions_map : (string * string, decision) Hashtbl.t Atomic.t =
  Atomic.make (Hashtbl.create 16)
;;

let key_of (d : decision) = d.exchange, d.symbol
let publish_generation : int Atomic.t = Atomic.make 0
let get_publish_generation () = Atomic.get publish_generation
let decisions () = Atomic.get decisions_ref

let decision_for ~(exchange : string) ~(symbol : string) : decision option =
  Hashtbl.find_opt (Atomic.get decisions_map) (exchange, symbol)
;;

let tracks_asset ~(exchange : string) ~(symbol : string) : bool =
  Hashtbl.mem (Atomic.get decisions_map) (exchange, symbol)
;;

let publish ~(on_publish : string list -> decision list -> unit) (fresh : decision list) =
  let prev = Atomic.get decisions_map in
  let next = Hashtbl.copy prev in
  List.iter (fun d -> Hashtbl.replace next (key_of d) d) fresh;
  (* Changed symbols: anything new, removed, or whose activity/sizing moved. *)
  let changed =
    List.filter
      (fun (d : decision) ->
         match Hashtbl.find_opt prev (key_of d) with
         | None -> true
         | Some old ->
           old.active <> d.active
           || Float.abs (old.grid_interval -. d.grid_interval) > 1e-12
           || Float.abs (old.buy_qty -. d.buy_qty) > 1e-12
           || Float.abs (old.sell_qty -. d.sell_qty) > 1e-12)
      fresh
    |> List.map (fun (d : decision) -> d.symbol)
  in
  Atomic.set decisions_ref fresh;
  Atomic.set decisions_map next;
  Atomic.incr publish_generation;
  if changed <> [] then on_publish changed fresh
;;

