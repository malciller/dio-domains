(* Wake / lifecycle *)
(* ------------------------------------------------------------------ *)

let shutdown_requested = Atomic.make false
let is_stopped () = Atomic.get shutdown_requested
let shutdown () = Atomic.set shutdown_requested true
let pass_requested : int Atomic.t = Atomic.make 0

(** Domain-safe wake channel for [request_pass].

    [request_pass] is called from venue feed threads and domain workers (the
    [Oracle_wakeup] doorbell); [wait_event] runs on the main Lwt domain. [Lwt_condition]
    is not safe off the Lwt domain: a worker would race the scheduler on Lwt's
    unsynchronized waiter list and a wake could run the oracle continuation on the trading
    domain's stack, inflating execution latency. Instead a self-pipe (as in
    [Strategy_common.OrderSignal]) lets a non-blocking byte write from any domain wake the
    Lwt read without touching Lwt internals. *)
let wake_read_fd, wake_write_fd =
  let r, w = Unix.pipe ~cloexec:true () in
  Unix.set_nonblock r;
  Unix.set_nonblock w;
  r, w
;;

(** Lwt wrapper for the read end of the self-pipe. Created once at module init to avoid
    per-wait allocation. *)
let wake_lwt_read_fd =
  Lwt_unix.of_unix_file_descr ~blocking:false ~set_flags:false wake_read_fd
;;

(** Coalesces multiple [request_pass] calls into a single pipe write. The monotonically
    increasing [pass_requested] counter carries the actual wake semantics, so dropping a
    coalesced byte is always recovered by the waiter's predicate recheck. *)
let wake_pending = Atomic.make false

(** Reusable one-byte payload; [Unix.write] never mutates it. *)
let wake_byte = Bytes.make 1 '\x00'

(** The pass loop sets this while it is computing. A producer that rings the doorbell
    during a pass only bumps [pass_requested]; the loop's post-pass predicate recheck
    consumes it, so no pipe write (and no syscall) is needed. *)
let pass_running = Atomic.make false

(** Requests a pass and wakes the oracle loop. Safe from any domain: the counter increment
    and, only when the consumer is parked, one coalesced non-blocking pipe write. *)
let request_pass () =
  Atomic.incr pass_requested;
  if (not (Atomic.get pass_running)) && not (Atomic.exchange wake_pending true)
  then (
    try ignore (Unix.write wake_write_fd wake_byte 0 1) with
    | Unix.Unix_error (Unix.EAGAIN, _, _) -> ()
    | Unix.Unix_error (Unix.EWOULDBLOCK, _, _) -> ()
    | _ -> ())
;;

(** Lwt-side wake fan-out, touched only on the main Lwt domain: the pump fiber below
    drains the self-pipe and broadcasts this condition; the pass and refresh waiters park
    on it. Domain workers never touch Lwt.

    A self-pipe read fd is single-reader: two concurrent [Lwt_unix.wait_read] waiters
    (pass loop and refresh loop) could race to consume one coalesced byte, leaving the
    loser parked. Funnelling wakes through one pump fiber and broadcasting a condition
    gives all-waiter wake semantics without Lwt calls from a worker domain. *)
let wake_condition : unit Lwt_condition.t = Lwt_condition.create ()

let waker_started = Atomic.make false

(** Single reader of the self-pipe. Drains every pending byte, clears [wake_pending], then
    broadcasts to all Lwt waiters. Because the broadcast happens after each drain, a
    [request_pass] that coalesces into an existing pending byte is still covered by this
    iteration's broadcast (or by the waiter's predicate re-check). *)
let rec pump_wake () =
  Lwt_unix.wait_read wake_lwt_read_fd
  >>= fun () ->
  let buf = Bytes.create 64 in
  (try
     while true do
       let n = Unix.read wake_read_fd buf 0 64 in
       if n = 0 then raise Exit
     done
   with
   | _ -> ());
  Atomic.set wake_pending false;
  Lwt_condition.broadcast wake_condition ();
  (* Spawn the next reader independently: chaining it with [>>=] would leave one Lwt
     Forward node behind per doorbell for the life of the process. *)
  Lwt.async pump_wake;
  Lwt.return_unit
;;

(** Starts the pump fiber. Idempotent; must run on the main Lwt domain. *)
let start_waker () =
  if Atomic.compare_and_set waker_started false true then Lwt.async pump_wake
;;

let pass_requested_changed generation = Atomic.get pass_requested <> generation

(** Event-only wait for the control loop: blocks until a pass request or shutdown. No
    deadline, because every input transition rings the doorbell. The periodic history /
    balance refresh still calls [request_pass] when it completes, so a restarted or
    recovered feed also wakes the loop. *)
let wait_event ~(generation : int) () =
  let finished, finished_u = Lwt.wait () in
  let finish () = if Lwt.is_sleeping finished then Lwt.wakeup_later finished_u () in
  let rec loop () =
    if is_stopped () || pass_requested_changed generation
    then (
      finish ();
      Lwt.return_unit)
    else (
      start_waker ();
      let w = Lwt_condition.wait wake_condition in
      (* Close the race between the predicate check above and registering the waiter. *)
      if is_stopped () || pass_requested_changed generation
      then Lwt_condition.broadcast wake_condition ();
      w
      >>= fun () ->
      (* A spurious broadcast (or a wake for an unrelated waiter) must not accumulate a
         recursive [>>=] chain: park again from a freshly-spawned iteration. *)
      if is_stopped () || pass_requested_changed generation
      then (
        finish ();
        Lwt.return_unit)
      else (
        Lwt.async loop;
        Lwt.return_unit))
  in
  Lwt.async loop;
  finished
;;

