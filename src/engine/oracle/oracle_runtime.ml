(* Oracle runtime - event-driven capital allocation across venues.

   One pass re-resolves every configured asset: all-time merged price
   history -> references -> runway -> survival-replay parameter search ->
   decision record, sized against per-venue pools walked in CONFIG
   PRESENTATION ORDER (first entry = highest priority; capacity passes down;
   a lower-priority strategy is never starved while quote exists). Pools are
   PER VENUE: one quote pool shared by that venue's strategies, never
   crossing venues.

   The hot path is pure arithmetic over in-process state (<10ms p99):
   - price history lives in a cache refreshed on a background cadence
     ([refresh_seconds] fallback poll);
   - balances come from the websocket-fed live store when present, otherwise
     the last fetched snapshot, adjusted IN PROCESS by fill/cancel deltas
     (notify_fill / notify_order_cancel) so events never wait on network;
   - live prices read the in-process top-of-book with a sane-band check
     against the last bar close.

   Events coalesce into a single re-resolve: fills, cancels, balance
   changes, and explicit requests all just wake the loop; one pass consumes
   everything pending.

   Strategy-facing contract: exactly four values per asset - [active],
   [grid_interval], [buy_qty], [sell_qty] - generated by exactly one code
   path (the pass below) and consumed everywhere. Values are emitted for
   inactive strategies too, for visibility, pool accounting, and immediate
   reactivation eligibility. All normalization happens at the exchange
   layer. Diagnostics ([reason], [d_surv], [regime], [branch]) exist for
   logs and dio-oracle output only. *)

module Exchange = Dio_exchange.Exchange_intf
open Lwt.Infix

let section = "oracle_runtime"

